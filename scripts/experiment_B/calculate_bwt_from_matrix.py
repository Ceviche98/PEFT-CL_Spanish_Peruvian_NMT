#!/usr/bin/env python3
"""
Triangular Evaluation Matrix Reader & BWT / FM Calculator (Experiment B)
========================================================================
Reads any `triangular_eval_matrix.json` generated by `train_lora_sequential.py`
and instantly calculates:
  1. Average Accuracy (AA) across all 5 languages
  2. Forgetting Measure (FM) (both mean and per-language: max - final)
  3. Backward Transfer (BWT) (both mean and per-language: final - diagonal)

Usage:
  python scripts/experiment_B/calculate_bwt_from_matrix.py path/to/triangular_eval_matrix.json [--order order1]
"""

import argparse
import json
import sys
from pathlib import Path
import numpy as np

ORDERS = {
    "order1": ["quy", "ayr", "shp", "agr", "cni"],
    "order2": ["cni", "agr", "shp", "ayr", "quy"],
}

def analyze_triangular_matrix(matrix_path: Path, order_name: str = None):
    if not matrix_path.exists():
        print(f"CRITICAL ERROR: File not found at {matrix_path}")
        sys.exit(1)

    with open(matrix_path, "r", encoding="utf-8") as f:
        eval_matrix = json.load(f)

    # Detect order if not explicitly specified
    if not order_name:
        trained_langs = list(eval_matrix.keys())
        if trained_langs == ORDERS["order1"][:len(trained_langs)]:
            order_name = "order1"
        elif trained_langs == ORDERS["order2"][:len(trained_langs)]:
            order_name = "order2"
        else:
            print(f"Could not automatically match order for keys: {trained_langs}. Assuming custom order.")
            order_name = "custom"
            order_langs = trained_langs
    
    if order_name in ORDERS:
        order_langs = ORDERS[order_name]
    else:
        order_langs = list(eval_matrix.keys())

    print("\n" + "═" * 70)
    print(f" TRIANGULAR EVALUATION MATRIX ANALYSIS ({order_name.upper()})")
    print("═" * 70)

    # Print ASCII table
    header = "Task Trained \\ Dev Eval | " + " | ".join([f"{lc.upper():10s}" for lc in order_langs])
    print(header)
    print("-" * len(header))
    for t_lang in order_langs:
        if t_lang in eval_matrix:
            row_str = f"{t_lang.upper():21s} | "
            for k_lang in order_langs:
                val = eval_matrix[t_lang].get(k_lang, "---")
                row_str += f"{str(val):10s} | "
            print(row_str)

    final_lang = order_langs[-1]
    if final_lang not in eval_matrix:
        print(f"\nWARNING: Matrix is incomplete (final task '{final_lang}' not evaluated yet).")
        return

    final_scores = eval_matrix[final_lang]
    aa = np.mean(list(final_scores.values()))
    print(f"\n---> Average Accuracy (AA) across all 5 languages: {aa:.2f} chrF++")

    forgetting_vals = {}
    bwt_vals = {}
    for k_lang in order_langs[:-1]:
        max_k = max([eval_matrix[t_lang].get(k_lang, 0.0) for t_lang in eval_matrix])
        diag_k = eval_matrix.get(k_lang, {}).get(k_lang, 0.0)
        final_k = final_scores.get(k_lang, 0.0)
        forgetting_vals[k_lang] = round(max_k - final_k, 2)
        bwt_vals[k_lang] = round(final_k - diag_k, 2)

    mean_fm = np.mean(list(forgetting_vals.values())) if forgetting_vals else 0.0
    mean_bwt = np.mean(list(bwt_vals.values())) if bwt_vals else 0.0

    print(f"---> Mean Forgetting Measure (FM): {mean_fm:.2f} chrF++ drop across past tasks")
    print(f"     Per-language Forgetting (max - final): {forgetting_vals}")
    print(f"---> Mean Backward Transfer (BWT): {mean_bwt:+.2f} chrF++ change across past tasks")
    print(f"     Per-language BWT (final - diag):       {bwt_vals}")

    summary_out = matrix_path.parent / "continual_learning_summary_recomputed.json"
    summary_data = {
        "order": order_name,
        "average_accuracy_AA": round(aa, 2),
        "mean_forgetting_measure_FM": round(mean_fm, 2),
        "mean_backward_transfer_BWT": round(mean_bwt, 2),
        "per_language_forgetting": forgetting_vals,
        "per_language_bwt": bwt_vals,
        "triangular_matrix": eval_matrix
    }
    with open(summary_out, "w", encoding="utf-8") as f:
        json.dump(summary_data, f, indent=2, ensure_ascii=False)
    print(f"\n✓ Saved recomputed metrics summary to: {summary_out}")
    print("═" * 70 + "\n")


def main():
    parser = argparse.ArgumentParser(description="Calculate AA, FM, and BWT from triangular_eval_matrix.json")
    parser.add_argument("matrix_path", type=str, help="Path to triangular_eval_matrix.json")
    parser.add_argument("--order", type=str, default=None, choices=["order1", "order2"], help="Explicit order name")
    args = parser.parse_args()

    analyze_triangular_matrix(Path(args.matrix_path), args.order)


if __name__ == "__main__":
    main()
